import random

print("--- კეთილი იყოს შენი მობრძანება მარის რიცხვების გამოცნობის თამაშში ---")

# 1. გარე ციკლი მართავს მთლიან თამაშს (თავიდან თამაშის ლოგიკა)
while True:
    
    # კომპიუტერი იფიქრებს რიცხვს 1-დან 20-მდე დიაპაზონში
    secret_number = random.randint(1, 20)
    
    attempts = 0
    max_attempts = 5  # მაქსიმალური მცდელობების ლიმიტი
    
    print(f"\nმე ჩავიფიქრე რიცხვი 1-დან 20-მდე.")
    print(f"შენ გაქვს {max_attempts} ცდა მის გამოსაცნობად.წარმატებები!")
    
    # 2. შიდა ციკლი მართავს უშუალოდ გამოცნობის პროცესს
    while attempts < max_attempts:
        try:
            # ვითხოვთ რიცხვს შესაყვანად
            guess = int(input(f"\nმცდელობა {attempts + 1} / {max_attempts}-დან. შეიყვანე რიცხვი 1-დან 20-მდე: "))
            
            # შევამოწმოთ, არის თუ არა რიცხვი 1-სა და 20-ს შორის
            if not (1 <= guess <= 20):
                print("⚠️ შეცდომა: უნდა შეიყვანოთ მხოლოდ რიცხვი 1-დან 20-მდე! ეს ცდა არ ჩაგეთვალა.")
                continue  # 'continue' ტოვებს ამ იტერაციის დანარჩენ კოდს და ახლიდან იწყებს ციკლს
            
            # მხოლოდ ვალიდაციის გავლის შემდეგ ვზრდით მცდელობების რაოდენობას
            attempts += 1
            
            # ლოგიკის შემოწმება, არის თუ არა guess(secret_number)-ზე ნაკლები, მეტი, თუ სწორია
            if guess < secret_number:
                print("ჩემი ჩაფიქრებული რიცხვი უფრო დიდია!")
            elif guess > secret_number:
                print("ჩემი ჩაფიქრებული რიცხვი უფრო პატარაა!")
            else:
                print(f"სწორია! შენ გამოიცანი რიცხვი {attempts} მცდელობაში.")
                break  # ვწყვეტთ შიდა ციკლს, რადგან გამოიცნო
                
        except ValueError:
            # თუ მომხმარებელმა რიცხვის ნაცვლად ასოები ან სიმბოლოები შეიყვანა
            print("შეცდომა: უნდა შეიყვანოთ მხოლოდ რიცხვი 1-დან 20-მდე! ეს ცდა არ ჩაგეთვალა.")
            
    # 3. თუ შიდა ციკლი დასრულდა რიცხვის გამოცნობის გარეშე (else ბლოკი)
    else:
        print(f"\nთამაში დასრულდა! შენ ამოწურე ყველა ({max_attempts}) მცდელობა.")
        print(f"ჩაფიქრებული რიცხვი იყო: {secret_number}")

    # 4. ვეკითხებით, სურს თუ არა თავიდან თამაში
    play_again = input("\nგსურს თავიდან თამაში? (ჩაწერე 'yes' ან 'კი' გასაგრძელებლად, სხვა ნებისმიერი კლავიში გასასვლელად): ")
    
    if play_again.lower() not in ['yes', 'კი']:
        print("მადლობა თამაშისთვის! ნახვამდის.")
        break  # ვწყვეტთ გარე ციკლს და ვთიშავთ პროგრამას
    